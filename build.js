#!/usr/bin/env node
/**
 * build.js — 一键重建 output.svg + README.md，并带 --watch 调试模式。
 *
 * 用法：
 *   node build.js                  # 内置 Markdown → output.svg + README.md
 *   node build.js content.md       # 用指定 Markdown 文件
 *   node build.js --watch          # 保存 gen.js / font.js / 字体 / 内容 .md 后自动重建
 *   node build.js content.md -w    # 同上，内容来自 content.md
 *
 * 注意：watch 监听 gen.js、font.js、字体文件和内容文件；改 build.js 本身需要重启进程。
 *
 * README.md 的生成规则（所以不要直接手改它）：
 *   · 只内嵌 output.svg，不复制正文
 *   · 图片宽度跟随画布，alt 取自内容的第一个标题 / 引用
 *
 * 改内容 → 改 gen.js 里的 SAMPLE_MARKDOWN（或传自己的 .md）→ 重跑本脚本。
 */

'use strict';

const fs = require('node:fs');
const path = require('node:path');
let gen = require('./gen.js');

/** 重新加载 gen.js / font.js，让 watch 模式下的修改立即生效 */
function loadGen() {
  delete require.cache[require.resolve('./gen.js')];
  delete require.cache[require.resolve('./font.js')];
  return require('./gen.js');
}

/* ══════════════════════════════════════════════════════════════════
   1. 配置
   ══════════════════════════════════════════════════════════════════ */

const OUTPUTS = {
  svg: 'output.svg',
  readme: 'README.md',
};

const WATCH_DEBOUNCE_MS = 120;

const USAGE = `build.js — regenerate output.svg + README.md

Usage:
  node build.js                 type the built-in sample Markdown
  node build.js content.md      type your own Markdown file
  node build.js --watch         rebuild whenever gen.js / font.js / font / content.md changes
  node build.js content.md -w   both

Options:
  -w, --watch   watch sources and rebuild on save
  -h, --help    show this help
`;

/* ══════════════════════════════════════════════════════════════════
   2. 构建：SVG + README
   ══════════════════════════════════════════════════════════════════ */

/**
 * 重新编译 SVG 和 README。
 * @param {string} markdown 动画与 README 共用的内容源
 * @param {string} cwd 输出目录（默认当前目录）
 */
function buildAll(markdown, cwd = process.cwd()) {
  const plan = gen.build(markdown);
  const svg = gen.emitSvg(plan);
  const readme = renderReadme(plan, markdown);

  const svgPath = path.join(cwd, OUTPUTS.svg);
  const readmePath = path.join(cwd, OUTPUTS.readme);
  fs.writeFileSync(svgPath, svg, 'utf8');
  fs.writeFileSync(readmePath, readme, 'utf8');

  return {
    plan,
    svgPath,
    readmePath,
    svgBytes: Buffer.byteLength(svg),
    readmeBytes: Buffer.byteLength(readme),
  };
}

/**
 * 生成 README.md：只内嵌 output.svg，不再复制一遍正文。
 * 宽度跟随画布；alt 取自内容的第一个标题 / 引用，便于屏幕阅读器。
 */
function renderReadme(plan, markdown) {
  const title = firstMatch(markdown, /^#\s+(.+)$/m) || 'README';
  const tagline = firstMatch(markdown, /^>\s?(.+)$/m) || gen.DOCUMENT_TAGLINE;
  const alt = escapeAttribute([title, tagline].filter(Boolean).join(' - '));

  return [
    '<!-- generated by build.js — edit the source Markdown, then rebuild -->',
    '',
    '<p align="center">',
    `  <img src="./${OUTPUTS.svg}" width="${plan.width}" alt="${alt}">`,
    '</p>',
    '',
  ].join('\n');
}

/* ══════════════════════════════════════════════════════════════════
   3. 文件与日志小工具
   ══════════════════════════════════════════════════════════════════ */

function firstMatch(text, regex) {
  const match = regex.exec(String(text ?? ''));
  return match ? match[1].trim() : '';
}

function escapeAttribute(value) {
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

function seconds(ms) {
  return (ms / 1000).toFixed(2) + 's';
}

function clock() {
  return new Date().toLocaleTimeString('en-GB', { hour12: false });
}

function displayPath(filePath) {
  const relative = path.relative(process.cwd(), filePath);
  return relative && !relative.startsWith('..') ? relative : filePath;
}

function readSource(contentPath) {
  return contentPath ? fs.readFileSync(contentPath, 'utf8') : gen.SAMPLE_MARKDOWN;
}

function printBuild(result) {
  console.log(`✓ ${displayPath(result.svgPath)}  (${(result.svgBytes / 1024).toFixed(1)} KB)`);
  console.log(`✓ ${displayPath(result.readmePath)}  (${(result.readmeBytes / 1024).toFixed(1)} KB)`);
  console.log(
    `  ${result.plan.charCount} chars · ${result.plan.lineCount} lines · ` +
      `${seconds(result.plan.total)} timeline · ${result.plan.width}×${result.plan.height}`,
  );
}

/* ══════════════════════════════════════════════════════════════════
   4. watch 模式
   ══════════════════════════════════════════════════════════════════ */

function watchSources(contentPath, rebuild) {
  const targets = [
    path.join(__dirname, 'gen.js'),
    path.join(__dirname, 'font.js'),
    path.join(__dirname, gen.FONT.FILE),
    path.join(__dirname, 'github-langs.json'),
    path.join(__dirname, 'github-contributions.json'),
  ];
  if (contentPath) targets.push(contentPath);

  /** @type {Map<string, Set<string>>} dir -> basenames */
  const dirs = new Map();
  for (const file of targets) {
    const dir = path.dirname(file);
    if (!dirs.has(dir)) dirs.set(dir, new Set());
    dirs.get(dir).add(path.basename(file));
  }

  const watchers = [];
  for (const [dir, names] of dirs) {
    const watcher = fs.watch(dir, (eventType, filename) => {
      if (!filename || !names.has(filename)) return; // 忽略 output.svg / README.md
      rebuild(filename);
    });
    watcher.on('error', (error) => console.error(`✗ watcher: ${error.message}`));
    watchers.push(watcher);
  }

  console.log('');
  console.log(`watching ${targets.map((file) => path.basename(file)).join(', ')}`);
  console.log('press Ctrl+C to stop');

  const stop = () => {
    for (const watcher of watchers) watcher.close();
    console.log('\nstopped.');
    process.exit(0);
  };
  process.on('SIGINT', stop);
  process.on('SIGTERM', stop);
}

/* ══════════════════════════════════════════════════════════════════
   5. CLI
   ══════════════════════════════════════════════════════════════════ */

function parseArgs(argv) {
  const watch = argv.includes('--watch') || argv.includes('-w');
  const help = argv.includes('--help') || argv.includes('-h');
  const positional = argv.filter((arg) => !arg.startsWith('-'));
  const contentPath = positional.length ? path.resolve(process.cwd(), positional[0]) : null;
  return { watch, help, contentPath };
}

function main() {
  const options = parseArgs(process.argv.slice(2));

  if (options.help) {
    console.log(USAGE);
    return;
  }

  const readmePath = path.resolve(process.cwd(), OUTPUTS.readme);
  const svgPath = path.resolve(process.cwd(), OUTPUTS.svg);
  if (options.contentPath && [readmePath, svgPath].includes(path.resolve(options.contentPath))) {
    console.error('✗ the content file cannot be output.svg or README.md (this script overwrites them)');
    process.exitCode = 1;
    return;
  }

  try {
    const result = buildAll(readSource(options.contentPath));
    printBuild(result);
  } catch (error) {
    console.error(`✗ ${error.message}`);
    process.exitCode = 1;
    return;
  }

  if (!options.watch) return;

  let timer = null;
  const rebuild = (filename) => {
    if (timer) clearTimeout(timer);
    timer = setTimeout(() => {
      timer = null;
      console.log(`\n[${clock()}] change detected: ${filename} — rebuilding…`);
      try {
        gen = loadGen(); // gen.js 可能刚被改过，清掉 require 缓存再构建
        const result = buildAll(readSource(options.contentPath));
        printBuild(result);
      } catch (error) {
        console.error(`✗ ${error.message}`);
      }
    }, WATCH_DEBOUNCE_MS);
  };

  watchSources(options.contentPath, rebuild);
}

if (require.main === module) {
  main();
}

module.exports = {
  buildAll,
  renderReadme,
  parseArgs,
  OUTPUTS,
};
